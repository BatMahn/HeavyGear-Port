#!/usr/bin/env python3
"""Writes src/weapon_heat.h: the weapon table's heat (+0x44 float, 0x101192f0 + type x 0xd6) from HGSIM.DLL.
usage: gen_weapon_heat.py HGSIM.DLL > src/weapon_heat.h"""
import struct, sys
import pefile

def main():
    pe = pefile.PE(sys.argv[1])
    base = pe.OPTIONAL_HEADER.ImageBase
    def f32(va):
        return struct.unpack('<f', pe.get_data(va - base, 4))[0]
    n = 46
    vals = [f32(0x101192f0 + t * 0xd6 + 0x44) for t in range(n)]
    print('/* generated by tools/ref/gen_weapon_heat.py from HGSIM.DLL: the weapon table\'s +0x44 (0x101192f0 + type x')
    print(' * 0xd6), the heat an AI weighs against its skill row\'s limit when it arms its weapons together (0x10006473) */')
    print('#ifndef HG_WEAPON_HEAT_H')
    print('#define HG_WEAPON_HEAT_H')
    print('static const float weapon_heat[%d] = {' % n)
    for i in range(0, n, 8):
        print('    ' + ' '.join('%gf,' % v if v != int(v) else '%d.0f,' % v for v in vals[i:i + 8]))
    print('};')
    print('#endif')

main()

#!/usr/bin/env python3
"""Generate src/radio_text.h: the radio voice records' texts (HGSIM.DLL).

The voice records (0x18 bytes: the name, +0x10 the text pointer) get their text pointers at the sim's start by
0x100177d4 (mov reg, ds:[0x10187xxx]; mov ds:[record + 0x10], reg); those slots are the language table's lookups of
English keys (0x1009a... : mov ds:[0x10187xxx], eax after push <key>; call 0x100a0384). With no language table the key
is the text. Usage: gen_radio_text.py HGSIM.DLL > src/radio_text.h (needs objdump)."""
import re, struct, subprocess, sys

dll = sys.argv[1]
d = open(dll, 'rb').read()
pe = struct.unpack_from('<I', d, 0x3c)[0]
ns = struct.unpack_from('<H', d, pe + 6)[0]
so = pe + 24 + struct.unpack_from('<H', d, pe + 20)[0]
secs = [struct.unpack_from('<8sIIII', d, so + i * 40) for i in range(ns)]
def off(va):
    va -= 0x10000000
    for n, vs, v, rs, ro in secs:
        if v <= va < v + rs:
            return ro + va - v
    return None
def cstr(va):
    o = off(va)
    if o is None:
        return None
    return d[o:d.index(b'\0', o)].decode('latin-1')

asm = subprocess.run(['objdump', '-d', '-M', 'intel', '--no-show-raw-insn', dll], capture_output=True, text=True).stdout
lines = asm.split('\n')
# the language slots: push <key>; ... call 0x100a0384; ... mov ds:0x10187xxx,eax
slot = {}
last_push = None
for i, l in enumerate(lines):
    m = re.search(r'push\s+0x(10[0-9a-f]{6})$', l)
    if m:
        last_push = int(m.group(1), 16)
        continue
    m = re.search(r'mov\s+ds:0x(10187[0-9a-f]{3}),eax', l)
    if m and last_push is not None:
        # the call in between must be 0x100a0384
        back = '\n'.join(lines[max(0, i - 4):i])
        if '100a0384' in back:
            s = cstr(last_push)
            if s is not None:
                slot[int(m.group(1), 16)] = s
        last_push = None
# the records: in 0x100177d4 .. 0x10018300
recs = {}
reg = {}
for l in lines:
    m = re.match(r'\s*(1001[78][0-9a-f]{3}):\s+mov\s+(\w+),(?:DWORD PTR )?ds:0x(10187[0-9a-f]{3})', l)
    if m and 0x100177d4 <= int(m.group(1), 16) < 0x10018400:
        reg[m.group(2)] = int(m.group(3), 16)
        continue
    m = re.match(r'\s*(1001[78][0-9a-f]{3}):\s+mov\s+(?:DWORD PTR )?ds:0x(1010[0-9a-f]{4}),(\w+)', l)
    if m and 0x100177d4 <= int(m.group(1), 16) < 0x10018400 and m.group(3) in reg:
        recs[int(m.group(2), 16)] = reg[m.group(3)]
print('/* generated by tools/ref/gen_radio_text.py from HGSIM.DLL: the radio voice records\' names and texts (0x100177d4,')
print(' * the English keys of the language table 0x100a0384) */')
print('static const struct { const char *name, *text; } radio_text[] = {')
n = 0
for field, sl in sorted(recs.items()):
    o = off(field - 0x10)
    name = d[o:o + 16].split(b'\0')[0].decode('latin-1')
    t = slot.get(sl)
    if not name or t is None:
        continue
    print('    {"%s", "%s"},' % (name, t.replace('\\', '\\\\').replace('"', '\\"')))
    n += 1
print('};')
sys.stderr.write('%d records\n' % n)
